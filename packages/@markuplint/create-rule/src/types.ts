/** Everything `createRuleHelper` needs: the rule to create and where it goes. */
export type CreateRuleHelperParams = CreateRuleCreatorParams & {
	/** Where the generated rule is placed. */
	readonly purpose: CreateRulePurpose;
};

/** The rule to generate, independent of its destination. */
export type CreateRuleCreatorParams = {
	/** Plugin or directory name (kebab-case). Unused for `CONTRIBUTE_TO_CORE`. */
	readonly pluginName: string;
	/** Rule name (kebab-case). */
	readonly ruleName: string;
	readonly lang: CreateRuleLanguage;
	/** Whether to generate a spec file. */
	readonly needTest: boolean;
	/** Metadata for a core rule. Required for `CONTRIBUTE_TO_CORE`. */
	readonly core?: CreateRuleCreatorCoreParams;
};

/** Metadata of a rule generated for core (`category` goes to `meta.ts`, `severity` to `schema.json`). */
export type CreateRuleCreatorCoreParams = {
	readonly description: string;
	readonly category: string;
	readonly severity: string;
};

/** What `createRuleHelper` generated. */
export type CreateRuleHelperResult = {
	readonly files: readonly File[];
	/** Packages the generated rule needs at runtime. */
	readonly dependencies: readonly string[];
	/** Packages the generated rule needs for development and tests. */
	readonly devDependencies: readonly string[];
};

/** Language of the generated rule source. */
export type CreateRuleLanguage = 'JAVASCRIPT' | 'TYPESCRIPT';

/** Where the generated rule is placed: an existing project, a new package, or the markuplint repository. */
export type CreateRulePurpose = 'ADD_TO_PROJECT' | 'PUBLISH_AS_PACKAGE' | 'CONTRIBUTE_TO_CORE';

/** A file generated by `createRuleHelper`. */
export type File = {
	readonly ext: string;
	/** Base name without extension or test suffix. */
	readonly name: string;
	/** Full file name including the test suffix, but without extension. */
	readonly fileName: string;
	/** Whether this is a spec file. */
	readonly test: boolean;
	readonly destDir: string;
	readonly filePath: string;
};
